import assert from "node:assert/strict";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const casesFile = process.argv[2];
assert(casesFile, "Pass the cases.tsv generated by prepare-fixtures.sh");
for (const row of (await Bun.file(casesFile).text()).trim().split("\n")) {
  const [caseId, repo] = row.split("\t");
  const guide = await Bun.file(resolve(repo, "docs/notifications.md")).text();
  const examples = [...guide.matchAll(/```json\n([\s\S]*?)\n```/g)];
  assert.equal(examples.length, 2, caseId);
  const [, documentedRequest] = examples[0];
  const [, documentedResponse] = examples[1];
  const requestBody = JSON.parse(documentedRequest);
  const responseBody = JSON.parse(documentedResponse);
  const { handleNotifications } = await import(
    pathToFileURL(resolve(repo, "src/notifications.js")).href
  );
  const request = (body) => handleNotifications(new Request("http://localhost/notifications", {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body,
  }));
  const response = await request(documentedRequest);
  const actual = await response.json();
  const stale = caseId === "guide-before";
  assert.equal(response.status, stale ? 400 : 201, caseId);
  assert.deepEqual(actual, stale ? { error: "invalid_channel" } : responseBody, caseId);

  let correctedRequest = null;
  if (stale) {
    const updated = await request(JSON.stringify({ delivery: requestBody }));
    assert.equal(updated.status, 201, caseId);
    const body = await updated.json();
    assert.deepEqual(body, responseBody, caseId);
    correctedRequest = { status: updated.status, body };
  }

  const result = Bun.spawnSync([process.execPath, "test"], { cwd: repo });
  assert.equal(result.exitCode, 0, result.stderr.toString());
  console.log(JSON.stringify({
    caseId,
    requestBody,
    documentedResult: { status: 201, body: responseBody },
    observedResult: { status: response.status, body: actual },
    correctedRequest,
    fixtureTests: "pass",
  }));
}
