import assert from "node:assert/strict";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";

const casesFile = process.argv[2];
assert(casesFile, "Pass the cases.tsv generated by prepare-holdout.sh");
for (const row of (await Bun.file(casesFile).text()).trim().split("\n")) {
  const [caseId, repo] = row.split("\t");
  const guide = await Bun.file(resolve(repo, "docs/exports.md")).text();
  const example = guide.match(/```js\n([\s\S]*?)\n```/);
  assert(example, caseId);
  const { handleExports } = await import(pathToFileURL(resolve(repo, "src/exports.mjs")).href);
  const request = new Request("http://localhost/exports/current");
  const response = handleExports(request, 0);
  assert.equal(response.status, 429, caseId);
  const seconds = response.headers.get("Retry-After");
  assert.equal(seconds, "5", caseId);
  const delayMs = new Function("response", example[1] + "\nreturn delayMs;")(response);
  const retry = handleExports(request, delayMs);
  assert.equal(retry.status, caseId === "retry-delay-wrong" ? 429 : 200, caseId);
  console.log(JSON.stringify({ caseId, firstStatus: response.status, seconds, delayMs, retryStatus: retry.status }));
}
